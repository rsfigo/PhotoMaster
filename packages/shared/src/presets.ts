export const PRESET_BY_ID: ReadonlyMap<string, Preset> = new Map(PRESETS.map((p) => [p.id, p]));

export function presetsByCategory(): { category: string; presets: Preset[] }[] {
  return PRESET_CATEGORIES.map((category) => ({
    category,
    presets: PRESETS.filter((p) => p.category === category),
  })).filter((g) => g.presets.length > 0);
}

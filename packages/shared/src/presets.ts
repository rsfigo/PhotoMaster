/**
 * Vibe-Presets (§15).
 *
 * Presets sind AUSGANGSPUNKTE, keine fertigen Bearbeitungen. Sie enthalten nur
 * die Parameter, die den jeweiligen Look definieren — alles andere bleibt auf
 * dem Default. Wird ein Preset über "KI anpassen" angewendet, bekommt das
 * Modell diese Werte zusammen mit der Bildanalyse und verschiebt sie so, dass
 * sie zum konkreten Foto passen (z. B. weniger Lichter-Rücknahme, wenn der
 * Himmel ohnehin nicht überstrahlt ist).
 *
 * `vibe` ist die Textbeschreibung, die dabei an die KI übergeben wird.
 */

